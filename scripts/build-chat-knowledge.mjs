// Builds the chatbot's knowledge file: Jumin's knowledge base and resume (src/data/chat/)
// first, then the same project data the site renders, so the assistant can only say what
// the portfolio says. Output: chatbot-api/knowledge.js
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import profile from '../src/data/profile.json' with { type: 'json' }
import resume from '../src/data/chat/resume.json' with { type: 'json' }
import { allProjects, homepageProjectSlugs } from '../src/data/portfolio.js'

const here = path.dirname(fileURLToPath(import.meta.url))
const site = 'https://juminshin06.github.io'

const clean = value => (typeof value === 'string' ? value.replace(/\s+/g, ' ').trim() : '')
const line = (label, value) => (clean(value) ? `- ${label}: ${clean(value)}` : '')

function describeProject(project) {
  const facts = (project.facts || []).map(fact => `${fact.label}: ${fact.value}`).join('; ')
  const process = project.designProcess
  const processLines = process
    ? Object.entries(process).flatMap(([stage, detail]) => {
        if (!detail || typeof detail !== 'object') return []
        const text = Object.values(detail).filter(v => typeof v === 'string').map(clean).join(' ')
        return text ? [`  - ${stage}: ${text}`] : []
      })
    : []
  return [
    `### ${project.title}`,
    line('URL', `${site}/work/${project.slug}/`),
    line('Organization', project.organization),
    line('Year', project.year),
    line('Duration', project.duration),
    line('Role', project.role),
    line('Team', project.team),
    line('Category', project.category),
    line('Summary', project.summary),
    line('Contribution', project.contribution),
    line('Outcome', project.outcome),
    facts ? `- Facts: ${facts}` : '',
    processLines.length ? `- Design process:\n${processLines.join('\n')}` : '',
  ].filter(Boolean).join('\n')
}

const featured = homepageProjectSlugs.map(slug => allProjects.find(project => project.slug === slug)).filter(Boolean)
const others = allProjects.filter(project => !homepageProjectSlugs.includes(project.slug))

const knowledgeBase = readFileSync(path.join(here, '..', 'src', 'data', 'chat', 'knowledge-base.md'), 'utf8').trim()
const entries = (items, link = false) => items.flatMap(item => [
  `### ${item.title ? `${item.title} — ${item.organization}` : `${item.organization} — ${item.title}`} (${item.period})${link && item.slug ? ` · ${site}/work/${item.slug}/` : ''}`,
  ...item.highlights.map(highlight => `- ${highlight}`),
])
const resumeText = [
  '# Current resume (2026) — the most up-to-date source for titles, dates and numbers',
  '',
  '## Education',
  ...resume.education.map(item => `- ${item.school} — ${item.degree} (${item.period})`),
  '',
  '## Skills',
  ...Object.entries(resume.skills).map(([group, list]) => `- ${group}: ${list.join(', ')}`),
  '',
  '## Experience',
  ...resume.experience.flatMap(item => [`### ${item.organization} — ${item.title}${item.location ? `, ${item.location}` : ''} (${item.period})`, ...item.highlights.map(highlight => `- ${highlight}`)]),
  '',
  '## Selected projects',
  ...entries(resume.projects, true),
  '',
  '## Research & publications',
  ...entries(resume.research, true),
].join('\n')

const knowledge = [
  knowledgeBase,
  '',
  resumeText,
  '',
  '# Portfolio site data — project pages (use these URLs when linking)',
  '',
  '## Profile',
  line('Name', profile.name),
  line('Role', profile.role),
  line('Location', profile.location),
  line('Tagline', profile.tagline),
  line('Email', profile.email),
  line('LinkedIn', profile.linkedin),
  line('Google Scholar', profile.scholar),
  line('GitHub', profile.github),
  line('Resume', `${site}/assets/JuminShin_Resume.pdf`),
  line('Site pages', `${site}/ (work), ${site}/research/, ${site}/about/, ${site}/archive/, ${site}/life/`),
  '',
  '## Bio',
  ...profile.bio.map(clean),
  '',
  '## Experience',
  ...profile.experience.map(item => `- ${item.organization} — ${item.title} (${item.period}). ${clean(item.description)}`),
  '',
  '## Education',
  ...profile.education.map(item => `- ${item.school} — ${item.degree} (${item.period})${item.description ? `. ${clean(item.description)}` : ''}`),
  '',
  '## Publications',
  ...profile.publications.map(item => `- ${item.title}. ${item.authors}. ${item.venue}, ${item.year}.`),
  '',
  '## Recognition',
  ...profile.recognition.map(item => `- ${item.title} (${item.year})`),
  '',
  '## Capabilities',
  ...profile.capabilities.map(item => `- ${item.title}: ${clean(item.description || item.detail || '')}`),
  '',
  '## Featured projects (in portfolio order)',
  ...featured.map(describeProject),
  '',
  '## Other projects (archive)',
  ...others.map(describeProject),
].join('\n')

const target = path.join(here, '..', 'chatbot-api', 'knowledge.js')
writeFileSync(target, `// Generated by scripts/build-chat-knowledge.mjs — do not edit by hand.\nexport const knowledge = ${JSON.stringify(knowledge)}\n`)
console.log(`Wrote ${target} (${knowledge.length.toLocaleString()} characters, ~${Math.round(knowledge.length / 4).toLocaleString()} tokens)`)
